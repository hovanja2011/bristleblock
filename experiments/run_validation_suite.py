"""Run all validation experiments and collect their CSV/PNG diagnostics."""
import argparse
import csv
import subprocess
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SCRIPTS=(
 "bristlebots/experiments/free_motion_validation.py",
 "bristlebots/experiments/rotational_validation.py",
 "bristlebots/experiments/head_on_collision_validation.py",
 "bristlebots/experiments/oblique_collision_validation.py",
 "toner_tu/experiments/periodic_acoustic_convergence.py",
 "toner_tu/experiments/damped_acoustic_mode.py",
 "toner_tu/experiments/nonlinear_ordering_validation.py",
)
TABLES=("free_motion_validation.csv","rotational_convergence.csv","head_on_collision.csv",
 "oblique_collision.csv","periodic_acoustic_convergence.csv","damped_acoustic_mode.csv",
 "nonlinear_ordering.csv")

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--output-dir",default="results/validation")
    parser.add_argument("--no-show",action="store_true")
    args=parser.parse_args(); output=(ROOT/args.output_dir).resolve()
    output.mkdir(parents=True,exist_ok=True)
    for script in SCRIPTS:
        command=[sys.executable,str(ROOT/script),"--output-dir",str(output)]
        if args.no_show: command.append("--no-show")
        print("\\n>>> "+" ".join(command),flush=True)
        subprocess.run(command,cwd=ROOT,check=True)
    combined=[]
    for filename in TABLES:
        path=output/filename
        if not path.exists(): raise FileNotFoundError(path)
        with path.open(newline="") as stream:
            for row in csv.DictReader(stream):
                row["source_file"]=filename; combined.append(row)
    keys=sorted({k for row in combined for k in row})
    with (output/"summary.csv").open("w",newline="") as stream:
        writer=csv.DictWriter(stream,fieldnames=keys); writer.writeheader(); writer.writerows(combined)
    (output/"README.md").write_text(
      "# Validation suite outputs\\n\\nGenerated by experiments/run_validation_suite.py.\\n\\n"
      "The experiment-specific CSV files preserve each metric's units and meaning. "
      "summary.csv concatenates their rows; do not compare unlike error measures without "
      "consulting the corresponding benchmark description.\\n\\n"
      "PNG figures show analytical/reference comparisons and refinement trends. "
      "Animations are interactive and are opened by individual experiments.\\n")
    print(f"Validation suite complete. Results: {output}")
if __name__=="__main__": main()
