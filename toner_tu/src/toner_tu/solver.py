"""SSP-RK3 integration and state-dependent explicit time-step control."""

import numpy as np

from toner_tu.domain import DomainOperators
from toner_tu.equations import compute_rhs
from toner_tu.fields import Fields, Grid
from toner_tu.parameters import TonerTuParameters


def max_stable_dt(
    fields: Fields,
    grid: Grid,
    params: TonerTuParameters,
    cfl: float = 0.4,
) -> float:
    """Return a conservative *estimate* of the explicit time-step limit.

    The estimate includes advective transport, the linearized density/velocity
    wave speed, explicit diffusion and the local cubic ordering reaction.
    It is a CFL safeguard for the implemented operators, not a proof of
    nonlinear stability for arbitrary future discretizations.
    """
    if not np.isfinite(cfl) or not 0.0 < cfl <= 1.0:
        raise ValueError("cfl must be finite and in (0, 1].")

    expected = (grid.ny, grid.nx)
    arrays = (fields.rho, fields.vx, fields.vy)
    if any(a.shape != expected for a in arrays):
        raise ValueError(f"All fields must have shape {expected}.")
    if not all(np.isfinite(a).all() for a in arrays):
        raise ValueError("Fields must contain only finite values.")
    if np.any(fields.rho < 0):
        raise ValueError("Density must be non-negative.")

    wave_speed = float(np.sqrt(params.sigma * np.max(fields.rho)))
    speed_x = float(np.max(np.abs(fields.vx))) * max(1.0, abs(params.lambda_))
    speed_y = float(np.max(np.abs(fields.vy))) * max(1.0, abs(params.lambda_))
    advective_rate = (
        (speed_x + wave_speed) / grid.dx
        + (speed_y + wave_speed) / grid.dy
    )

    diffusion_rate = 2.0 * params.diffusion * (
        grid.dx**-2 + grid.dy**-2
    )
    speed_sq = fields.vx**2 + fields.vy**2
    reaction_rate = float(
        np.max(abs(params.alpha) + 3.0 * params.beta * speed_sq)
    )

    total_rate = advective_rate + diffusion_rate + reaction_rate
    return float("inf") if total_rate == 0.0 else cfl / total_rate


def _combine(a: Fields, b: Fields, wa: float, wb: float) -> Fields:
    """Return the weighted sum wa*a + wb*b for all three state fields."""
    return Fields(
        wa * a.rho + wb * b.rho,
        wa * a.vx + wb * b.vx,
        wa * a.vy + wb * b.vy,
    )


def _validate_stage(fields: Fields, stage_name: str) -> None:
    """Reject non-finite states and negative physical density at RK stages."""
    if np.any(fields.rho < 0.0) or not all(
        np.isfinite(a).all() for a in (fields.rho, fields.vx, fields.vy)
    ):
        raise ValueError(f"{stage_name} produced an invalid state.")


def _check_stage_stability(
    fields: Fields,
    grid: Grid,
    params: TonerTuParameters,
    dt: float,
    cfl: float,
    stage_name: str,
) -> None:
    stage_limit = max_stable_dt(fields, grid, params, cfl=cfl)
    if dt > stage_limit * (1.0 + 1e-12):
        raise ValueError(
            f"dt={dt:g} exceeds estimated stable step {stage_limit:g} "
            f"at {stage_name}; reduce dt or use integrate()."
        )


def step(
    fields: Fields,
    grid: Grid,
    params: TonerTuParameters,
    dt: float,
    domain: DomainOperators | None = None,
    *,
    check_stability: bool = True,
    cfl: float = 0.4,
) -> Fields:
    """Advance one third-order SSP Runge–Kutta step.

    SSP-RK2 is not stable for purely imaginary eigenvalues generated by
    centred periodic advection/acoustic operators: its stability polynomial
    amplifies every nonzero imaginary mode. SSP-RK3 has a finite stable
    interval on the imaginary axis and retains the strong-stability-preserving
    convex-combination structure.
    """
    if not np.isfinite(dt) or dt <= 0.0:
        raise ValueError("Time step dt must be finite and positive.")
    if check_stability:
        _check_stage_stability(fields, grid, params, dt, cfl, "initial state")

    # Shu–Osher SSP-RK3 stages.
    rhs0 = compute_rhs(fields, grid, params, domain)
    stage1 = Fields(
        fields.rho + dt * rhs0.rho,
        fields.vx + dt * rhs0.vx,
        fields.vy + dt * rhs0.vy,
    )
    _validate_stage(stage1, "First RK stage")
    if check_stability:
        _check_stage_stability(stage1, grid, params, dt, cfl, "first RK stage")

    rhs1 = compute_rhs(stage1, grid, params, domain)
    euler2 = Fields(
        stage1.rho + dt * rhs1.rho,
        stage1.vx + dt * rhs1.vx,
        stage1.vy + dt * rhs1.vy,
    )
    _validate_stage(euler2, "Second Euler stage")
    stage2 = _combine(fields, euler2, 0.75, 0.25)
    _validate_stage(stage2, "Second RK stage")
    if check_stability:
        _check_stage_stability(stage2, grid, params, dt, cfl, "second RK stage")

    rhs2 = compute_rhs(stage2, grid, params, domain)
    euler3 = Fields(
        stage2.rho + dt * rhs2.rho,
        stage2.vx + dt * rhs2.vx,
        stage2.vy + dt * rhs2.vy,
    )
    _validate_stage(euler3, "Third Euler stage")
    result = _combine(fields, euler3, 1.0 / 3.0, 2.0 / 3.0)
    _validate_stage(result, "SSP-RK3 step")
    return result


def integrate(
    fields: Fields,
    grid: Grid,
    params: TonerTuParameters,
    dt: float,
    n_steps: int,
    domain: DomainOperators | None = None,
    *,
    cfl: float = 0.4,
) -> Fields:
    """Integrate output intervals with state-dependent adaptive substepping.

    dt is the requested physical interval per outer step. The estimated
    stability limit is recomputed after each accepted substep and at every
    Runge–Kutta stage. If a stage becomes more restrictive than the initial
    estimate, the trial substep is halved and retried from the unchanged state.
    """
    if not np.isfinite(dt) or dt <= 0.0:
        raise ValueError("Time step dt must be finite and positive.")
    if not isinstance(n_steps, int) or isinstance(n_steps, bool) or n_steps < 0:
        raise ValueError("n_steps must be a non-negative integer.")
    if not np.isfinite(cfl) or not 0.0 < cfl <= 1.0:
        raise ValueError("cfl must be finite and in (0, 1].")

    current = fields.copy()
    for _ in range(n_steps):
        remaining = dt
        while remaining > 1e-14 * dt:
            stable_dt = max_stable_dt(current, grid, params, cfl=cfl)
            sub_dt = remaining if np.isinf(stable_dt) else min(remaining, stable_dt)

            while True:
                try:
                    candidate = step(
                        current, grid, params, sub_dt, domain,
                        check_stability=True, cfl=cfl,
                    )
                except ValueError as error:
                    if "exceeds estimated stable step" not in str(error):
                        raise
                    sub_dt *= 0.5
                    if sub_dt <= np.finfo(float).eps * dt:
                        raise RuntimeError(
                            "Adaptive time step underflow while enforcing stability."
                        ) from error
                    continue
                break

            current = candidate
            remaining -= sub_dt
    return current
